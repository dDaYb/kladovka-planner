require('node:fs').mkdirSync('test-results',{recursive:true});
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||undefined,headless:true,args:['--enable-unsafe-swiftshader']});
 const page=await browser.newPage({viewport:{width:1600,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.PLANNER_URL||'http://127.0.0.1:8765');
 await page.waitForFunction(()=>window.renderWebGL&&items.length===4);
 await page.evaluate(()=>{items=[];nextUid=1;addItem('se_900_500','left',40);});
 const rackId=await page.evaluate(()=>items[0].uid);
 assert.equal(await page.evaluate(id=>{ensureShelfLayout(items.find(i=>i.uid===id));return items[0].shelves;},rackId),5);
 assert.equal(await page.evaluate(()=>items[0].shelfZs.length),5);
 await page.evaluate(id=>setShelfCount(id,4),rackId);
 assert.deepEqual(await page.evaluate(()=>[items[0].shelves,items[0].shelfZs.length]),[4,4]);
 await page.evaluate(id=>{setShelfZ(id,1,900);},rackId);
 assert.equal(await page.evaluate(()=>items[0].shelfZs[1]%25),0);
 await page.evaluate(id=>{activeShelfIndex=1;addCargoToRack(id,'fix_18l',1);addCargoToRack(id,'fix_6l',1);},rackId);
 assert.equal(await page.evaluate(()=>items[0].contents.length),2);
 assert.equal(await page.evaluate(()=>items[0].contents[0].shelfIndex),1);
 assert.match(await page.evaluate(()=>items[0].contents[0].id),/^c_\d+$/);
 assert.ok(Array.isArray(await page.evaluate(()=>items[0].contents[0].inventory)));
 assert.equal(await page.evaluate(()=>items[0].contents[0].photo),null);
 const firstId=await page.evaluate(()=>items[0].contents[0].id);
 await page.evaluate(({id,cargoId})=>moveCargoToShelf(id,cargoId,0),{id:rackId,cargoId:firstId});
 assert.equal(await page.evaluate(id=>items[0].contents.find(c=>c.id===id).shelfIndex,firstId),0);
 await page.evaluate(id=>{activeShelfIndex=1;addCargoToRack(id,'fix_3l',1);},rackId);
 const ids=await page.evaluate(()=>shelfCargo(items[0],1).map(c=>c.id));
 assert.ok(ids.length>=2);
 await page.evaluate(({rackId,cargoId})=>reorderCargo(rackId,cargoId,1),{rackId,cargoId:ids[0]});
 const ids2=await page.evaluate(()=>shelfCargo(items[0],1).map(c=>c.id));
 assert.notEqual(ids2[0],ids[0]);
 const clear=await page.evaluate(()=>shelfClearance(items[0],1));
 assert.ok(clear>0);
 await page.evaluate(()=>{const tall=items[0].contents.find(c=>c.shelfIndex===1);tall.h=5000;});
 assert.ok((await page.evaluate(()=>shelfIssues(items[0]))).length>0);
 await page.evaluate(()=>{items[0].contents.forEach(c=>{if(c.h>1000)c.h=200;});});
 assert.equal((await page.evaluate(()=>shelfIssues(items[0]))).length,0);
 const snap=await page.evaluate(()=>snapshot());
 assert.equal(snap.shelfLayout,1);
 assert.equal(snap.cargoIds,1);
 assert.equal(snap.items[0].shelves,4);
 assert.ok(snap.items[0].contents[0].id);
 await page.reload();
 await page.waitForFunction(()=>window.renderWebGL);
 await page.evaluate(s=>loadSnapshot(s),snap);
 assert.equal(await page.evaluate(()=>items[0].shelves),4);
 assert.equal(await page.evaluate(()=>items[0].contents.length),3);
 assert.match(await page.evaluate(()=>items[0].contents[0].id),/^c_\d+$/);
 await page.screenshot({path:'test-results/shelf-cargo.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS: shelf count, heights, cargo ids, reorder, clearance, persistence');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
